// -----------------------------------------------------------------------
// Proposal gating: WASM must be rejected when WideArithmetic is disabled
// -----------------------------------------------------------------------
TEST(WideArithGating, RejectedWhenDisabled) {
  Configure Conf;
  Conf.removeProposal(Proposal::WideArithmetic);
  VM::VM VMInst(Conf);
  // The loader calls isInstrNeedProposal() and must reject the module.
  EXPECT_FALSE(VMInst.loadWasm(WideArithWasm));
}

TEST(WideArithGating, AcceptedWhenEnabled) {
  Configure Conf;
  Conf.addProposal(Proposal::WideArithmetic);
  VM::VM VMInst(Conf);
  EXPECT_TRUE(VMInst.loadWasm(WideArithWasm));
  EXPECT_TRUE(VMInst.validate());
  EXPECT_TRUE(VMInst.instantiate());
}

// -----------------------------------------------------------------------
// Serializer roundtrip: load -> serialize -> reload -> execute
// -----------------------------------------------------------------------
TEST(WideArithRoundtrip, SerializerRoundtrip) {
  Configure Conf;
  Conf.addProposal(Proposal::WideArithmetic);

  // Step 1: Parse to AST
  Loader::Loader Ldr(Conf);
  auto ModRes = Ldr.parseModule(WideArithWasm);
  ASSERT_TRUE(ModRes);

  // Step 2: Serialize AST back to bytes
  Loader::Serializer Ser(Conf);
  auto SerRes = Ser.serializeModule(**ModRes);
  ASSERT_TRUE(SerRes);
  const std::vector<Byte> &SerBytes = *SerRes;

  // Serialized bytes must be non-empty and start with the WASM magic
  ASSERT_GE(SerBytes.size(), 8U);
  EXPECT_EQ(SerBytes[0], 0x00U);
  EXPECT_EQ(SerBytes[1], 0x61U);
  EXPECT_EQ(SerBytes[2], 0x73U);
  EXPECT_EQ(SerBytes[3], 0x6DU);

  // Step 3: Reload from serialized bytes and execute
  VM::VM VMInst(Conf);
  ASSERT_TRUE(VMInst.loadWasm(SerBytes));
  ASSERT_TRUE(VMInst.validate());
  ASSERT_TRUE(VMInst.instantiate());

  // Spot-check a few functions to confirm semantic correctness after roundtrip
  CheckResult(VMInst, "add128_carry", 0, 1);
  CheckResult(VMInst, "sub128_borrow", -1, 0);
  CheckResult(VMInst, "mul_wide_u_max", 1, -2);
  CheckResult(VMInst, "mul_wide_s_minval", 0, INT64_C(0x4000000000000000));
  CheckResult(VMInst, "mul_wide_s_min_neg1",
              std::numeric_limits<int64_t>::min(), 0);
}


// Helper: run a named export on an already-instantiated VM, expect (lo, hi).
static void CheckResult(VM::VM &VMInst, std::string_view Name,
                        int64_t ExpLo, int64_t ExpHi) {
  // Single-argument execute is unambiguous (avoids the 2-string_view overload).
  auto Res = VMInst.execute(Name);
  ASSERT_TRUE(Res) << "execute(" << Name << ") failed";
  ASSERT_EQ(Res->size(), 2U) << Name << ": expected 2 results";
  // Execute returns vector<pair<ValVariant, ValType>>; extract via .first.
  // Template call extracted to avoid '<' misparse inside EXPECT_EQ macro.
  int64_t Lo = (*Res)[0].first.get<int64_t>();
  int64_t Hi = (*Res)[1].first.get<int64_t>();
  EXPECT_EQ(Lo, ExpLo) << Name << " result_lo mismatch";
  EXPECT_EQ(Hi, ExpHi) << Name << " result_hi mismatch";
}

// -----------------------------------------------------------------------
// Interpreter fixture
// -----------------------------------------------------------------------
class WideArithInterp : public ::testing::Test {
protected:
  void SetUp() override {
    ASSERT_TRUE(VM.loadWasm(WideArithWasm));
    ASSERT_TRUE(VM.validate());
    ASSERT_TRUE(VM.instantiate());
  }
  // Proposal must be set before VM is constructed below (member init order),
  // not in SetUp() -- VM would already have copied Conf's state by then.
  Configure Conf{Proposal::WideArithmetic};
  VM::VM VM{Conf};
};

TEST_F(WideArithInterp, add128_zero) {
  CheckResult(VM, "add128_zero", 0, 0);
}
TEST_F(WideArithInterp, add128_carry) {
  // (UINT64_MAX, 0) + (1, 0) = (0, 1)  — carry propagates from lo to hi
  CheckResult(VM, "add128_carry", 0, 1);
}
TEST_F(WideArithInterp, add128_wrap) {
  // (UINT64_MAX, UINT64_MAX) + (1, 0) = (0, 0)  — 128-bit wraparound
  CheckResult(VM, "add128_wrap", 0, 0);
}
TEST_F(WideArithInterp, sub128_simple) {
  CheckResult(VM, "sub128_simple", 7, 0);
}
TEST_F(WideArithInterp, sub128_borrow) {
  // (0, 1) - (1, 0) = (UINT64_MAX, 0)  — borrow propagates from hi to lo
  CheckResult(VM, "sub128_borrow", -1, 0);
}
TEST_F(WideArithInterp, sub128_wrap) {
  // (0, 0) - (1, 0) = (UINT64_MAX, UINT64_MAX)  — 128-bit borrow/wrap
  CheckResult(VM, "sub128_wrap", -1, -1);
}
TEST_F(WideArithInterp, mul_wide_u_simple) {
  CheckResult(VM, "mul_wide_u_simple", 15, 0);
}
TEST_F(WideArithInterp, mul_wide_u_max) {
  // UINT64_MAX * UINT64_MAX = 0xFFFFFFFFFFFFFFFE_0000000000000001
  CheckResult(VM, "mul_wide_u_max", 1, -2);
}
TEST_F(WideArithInterp, mul_wide_u_one) {
  // UINT64_MAX * 1 = (UINT64_MAX, 0)
  CheckResult(VM, "mul_wide_u_one", -1, 0);
}
TEST_F(WideArithInterp, mul_wide_s_pos) {
  CheckResult(VM, "mul_wide_s_pos", 42, 0);
}
TEST_F(WideArithInterp, mul_wide_s_neg1) {
  // (-1) * (-1) = 1
  CheckResult(VM, "mul_wide_s_neg1", 1, 0);
}
TEST_F(WideArithInterp, mul_wide_s_negmix) {
  // (-1) * 2 = -2 as int128 -> lo=0xFFFFFFFFFFFFFFFE hi=0xFFFFFFFFFFFFFFFF
  CheckResult(VM, "mul_wide_s_negmix", -2, -1);
}
TEST_F(WideArithInterp, mul_wide_s_minval) {
  // INT64_MIN * INT64_MIN = 2^126 -> lo=0 hi=0x4000000000000000
  CheckResult(VM, "mul_wide_s_minval", 0,
              INT64_C(0x4000000000000000));
}
TEST_F(WideArithInterp, mul_wide_s_min_neg1) {
  // INT64_MIN * (-1) = 2^63 -> lo=0x8000000000000000 hi=0
  CheckResult(VM, "mul_wide_s_min_neg1",
              std::numeric_limits<int64_t>::min(), 0);
}

